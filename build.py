#!/usr/bin/env python3
"""Bundle the ES modules in js/ into dist/bundle.js (a classic script).

Classic scripts load from file://, so index.html works by double-clicking it,
no web server needed. Run `python3 build.py` after editing anything in js/.
"""
import base64
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).parent
ORDER = ["util.js", "api.js", "circuits.js", "data.js", "predict.js", "news.js", "live.js", "app.js"]

parts = []
for name in ORDER:
    src = (ROOT / "js" / name).read_text()
    # Drop import statements (single or multi-line).
    src = re.sub(r"^import\s[\s\S]*?from\s+['\"][^'\"]+['\"];\s*$", "", src, flags=re.M)
    # `export const/function/async function` -> plain declarations.
    src = re.sub(r"^export\s+(?=(const|let|function|async|class)\b)", "", src, flags=re.M)
    parts.append(f"// ---- {name} ----\n{src}")

out = ROOT / "dist" / "bundle.js"
out.parent.mkdir(exist_ok=True)
out.write_text("// Generated by build.py — edit the files in js/ instead.\n(() => {\n'use strict';\n" + "\n".join(parts) + "\n})();\n")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")

# Also emit a fully self-contained single file (handy for sharing or previews).
html = (ROOT / "index.html").read_text()
css = (ROOT / "css" / "styles.css").read_text()
js = out.read_text()
html = html.replace('<link rel="stylesheet" href="css/styles.css" />', f"<style>\n{css}\n</style>")
inline_js = "\n" + js.replace("</script", "<\\/script") + "\n"
html = html.replace('<script src="dist/bundle.js"></script>', f"<script>{inline_js}</script>")
# The single file has no external script, so allow exactly this inline script by hash.
digest = base64.b64encode(hashlib.sha256(inline_js.encode()).digest()).decode()
assert "script-src 'self' file:;" in html, "CSP script-src not found in index.html"
html = html.replace("script-src 'self' file:;", f"script-src 'sha256-{digest}';")
single = ROOT / "dist" / "pitwall.html"
single.write_text(html)
print(f"wrote {single.relative_to(ROOT)} ({single.stat().st_size // 1024} KB)")
